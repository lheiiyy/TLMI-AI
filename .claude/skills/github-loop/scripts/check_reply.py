#!/usr/bin/env python3
"""Check an agent reply before it is posted to a GitHub issue.

Usage: check_reply.py reply.md --turn N --add needs-leo --remove code-working [--from code|lead] [--session sonnet]
Prints a JSON report and exits 1 if anything is wrong.

Also importable: check(text, turn, add, remove, max_words, expect_from, session) returns the same report.

Rules:
- The loop:v1 header is the FIRST line, so an agent comment can never read as an owner
  keyword such as APPROVED. It names the expected author (`from=code` or `from=lead`),
  the expected turn and a known type.
- plan replies say phase=1; result, verdict and summary replies say phase=2.
- A phase 2 result names `pr=<number>` and `head=<40-character sha>`, so the review is
  tied to one exact commit.
- A verdict is from the Lead, names pr, head and verdict=approved|changes, and ends with
  the two lines `Reviewed head <sha>` and `VERDICT: APPROVED` or `VERDICT: CHANGES REQUESTED`
  that match the header (a trailing platform footer is ignored).
- A summary carries the five report lines: Implemented and tested, Reviewed, Merged,
  Deployed, Blocked or unverified.
- A plan, a phase 2 result, a verdict and a summary carry exactly one line
  `Model: <haiku|sonnet|opus>` naming the model that actually produced the reply, with an
  optional note in brackets. If the step wanted another tier, the note says
  `(wanted opus; ran inline, no subagent)` or `(via subagent)`, so the gap is never hidden.
  With --session (the model this task runs on), the line must name that model unless it says
  `via subagent`, so a Sonnet task cannot claim an Opus review.
- A plan reply also carries `Risk: low|normal|high`, `CI required: yes|no` and
  `Files in scope: <folders/ and files>`; the merge gate reads all three (high risk or a file
  outside the scope means the owner merges; CI required means checks must exist).
- A relayed approval quotes the owner's own words, and those words start with APPROVED:
  `APPROVED by <name> in chat on <date>: "APPROVED ..."`.
- Word limits: 150 by default, 250 for a summary, 400 for a verdict (findings need room).
  A link counts as one word.
- Labels: never add to-code; add exactly one hand-off label; remove code-working.
  Pass add=None to skip the label rules (a relayed approval changes no label).
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rules import declared_scope, scope_problems  # noqa: E402

HEADER = re.compile(r"<!--\s*loop:v1\s+([^>]*?)-->")
URL = re.compile(r"https?://\S+")
SHA = re.compile(r"\A[0-9a-f]{40}\Z")
ALLOWED_ADD = {"needs-leo", "done", "awaiting-approval", "to-review", "reviewed"}
TYPES = {"result", "question", "plan", "summary", "verdict", "approval"}
PHASE_FOR_TYPE = {"plan": "1", "summary": "2", "verdict": "2"}
LIMITS = {"summary": 250, "verdict": 400}
REPORT_LINES = ["implemented and tested", "reviewed", "merged", "deployed", "blocked or unverified"]
FOOTER = re.compile(r"\n-{3,}\s*\n_?Generated by \[Claude Code\].*\Z", re.DOTALL)
MODEL_LINE = re.compile(r"(?im)^Model:[ \t]*(haiku|sonnet|opus|fable)[ \t]*(\([^\n]*\))?[ \t]*$")
MODEL_ANY = re.compile(r"(?im)^Model[ \t]*:[^\n]*$")
WANTED = re.compile(r"\bwanted[ \t]+(haiku|sonnet|opus|fable)\b", re.I)
RISK_LINE = re.compile(r"(?im)^[ \t>*-]*risk[ \t]*:[ \t]*\**[ \t]*(low|normal|high)\b")
CI_LINE = re.compile(r"(?im)^[ \t>*-]*CI required[ \t]*:[ \t]*\**[ \t]*(yes|no)\b")
RELAY = re.compile(r"(?m)^APPROVED by [^\n]{1,60}? in chat on \d{4}-\d{2}-\d{2}: [\u201c\"]APPROVED\b")
FAMILIES = ("haiku", "sonnet", "opus", "fable")


def family(value):
    """'claude-sonnet-5-5', 'Sonnet 5.5' or 'sonnet' -> 'sonnet'; None when unknown."""
    low = (value or "").lower()
    if "mythos" in low:
        return "fable"
    return next((f for f in FAMILIES if f in low), None)


def model_problems(text, session=None):
    """Rules for the one `Model:` line an autopilot reply must carry."""
    found = MODEL_ANY.findall(FOOTER.sub("", text))
    good = [l for l in found if MODEL_LINE.match(l.strip())]
    if len(found) != 1 or len(good) != 1:
        return ["carry exactly one line `Model: <haiku|sonnet|opus>` naming the model that actually produced this "
                "reply; if the step wanted another tier, add `(wanted opus; ran inline, no subagent)` or "
                "`(via subagent)`"]
    m = MODEL_LINE.match(good[0].strip())
    ran, note = m.group(1).lower(), m.group(2) or ""
    wanted = WANTED.search(note)
    if wanted and wanted.group(1).lower() != ran and not re.search(r"\b(inline|subagent)\b", note, re.I):
        return ["the Model line says the step wanted another tier; add whether it ran inline or via subagent"]
    running = family(session)
    if running and ran != running and not re.search(r"\bvia subagent\b", note, re.I):
        return [f"the Model line names {ran}, but this task runs {running}: name {running} (add `wanted {ran}; ran "
                f"inline`), or say `via subagent` only if a {ran} subagent really did the step"]
    return []


def last_lines(text, n=2):
    body = FOOTER.sub("", text.rstrip())
    return [l.strip() for l in body.splitlines() if l.strip()][-n:]


def check(text, turn, add, remove, max_words=None, expect_from="code", session=None):
    problems = []
    rtype, fields = None, {}

    m = HEADER.match(text.lstrip())
    if not m:
        problems.append("the first line must be the <!-- loop:v1 ... --> header")
    else:
        fields = dict(kv.split("=", 1) for kv in m.group(1).split() if "=" in kv)
        rtype = fields.get("type")
        if fields.get("from") != expect_from:
            problems.append(f"header must say from={expect_from}")
        if fields.get("turn") != str(turn):
            problems.append(f"header turn must be {turn}, found {fields.get('turn')}")
        if rtype not in TYPES:
            problems.append("header type must be one of " + ", ".join(sorted(TYPES)))
        elif rtype in PHASE_FOR_TYPE and fields.get("phase") != PHASE_FOR_TYPE[rtype]:
            problems.append(f"a {rtype} reply must say phase={PHASE_FOR_TYPE[rtype]}")
        if rtype in ("verdict", "approval") and fields.get("from") != "lead":
            problems.append(f"only the Lead posts a {rtype}")
        if (rtype == "result" and fields.get("phase") == "2") or rtype == "verdict":
            if not str(fields.get("pr", "")).isdigit():
                problems.append("name the pull request: pr=<number>")
            if not SHA.match(str(fields.get("head", ""))):
                problems.append("name the exact commit: head=<40-character sha>")
        if rtype == "verdict":
            verdict = fields.get("verdict")
            if verdict not in ("approved", "changes"):
                problems.append("verdict must be approved or changes")
            want = ["Reviewed head " + str(fields.get("head")),
                    "VERDICT: APPROVED" if verdict == "approved" else "VERDICT: CHANGES REQUESTED"]
            if last_lines(text) != want:
                problems.append(f"the last two lines must be: {want[0]} / {want[1]}")
        if rtype in ("plan", "verdict", "summary") or (rtype == "result" and fields.get("phase") == "2"):
            problems += model_problems(text, session)
        if rtype == "plan":
            if not RISK_LINE.search(text):
                problems.append("a plan reply carries one line `Risk: low|normal|high` (high: the owner merges)")
            if not CI_LINE.search(text):
                problems.append("a plan reply carries one line `CI required: yes|no` (yes: checks must exist to merge)")
            problems += [f"a plan reply: {p}" for p in scope_problems(declared_scope(text))]
        if rtype == "summary":
            low = text.lower()
            missing = [l for l in REPORT_LINES if l + ":" not in low]
            if missing:
                problems.append("the summary needs these report lines: " + ", ".join(missing))
        if rtype == "approval" and not RELAY.search(text):
            problems.append('a relayed approval says `APPROVED by <name> in chat on <date>: "APPROVED ..."`, '
                            "quoting the owner's own words, which start with APPROVED")

    limit = max_words if max_words is not None else LIMITS.get(rtype, 150)
    body = URL.sub(" link ", HEADER.sub("", text))  # a link counts as one word
    words = len(body.split())
    if words > limit:
        problems.append(f"{words} words; limit is {limit}")

    if add is not None:
        if "to-code" in add:
            problems.append("an agent must never add to-code")
        if not set(add) & ALLOWED_ADD:
            problems.append("add exactly one of " + ", ".join(sorted(ALLOWED_ADD)))
        if len(set(add) & ALLOWED_ADD) > 1:
            problems.append("add only one hand-off label")
        if "code-working" not in remove:
            problems.append("remove code-working when replying")

    return {"ok": not problems, "words": words, "type": rtype, "fields": fields, "problems": problems}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("reply")
    ap.add_argument("--turn", type=int, required=True)
    ap.add_argument("--add", action="append", default=[])
    ap.add_argument("--remove", action="append", default=[])
    ap.add_argument("--from", dest="expect_from", choices=("code", "lead"), default="code")
    ap.add_argument("--max-words", type=int, default=None, help="default 150; 250 for a summary, 400 for a verdict")
    ap.add_argument("--session", default=None, help="the model this task runs on; the Model line must name it")
    args = ap.parse_args()

    with open(args.reply, encoding="utf-8") as f:
        text = f.read()
    report = check(text, args.turn, args.add, args.remove, args.max_words, args.expect_from, args.session)
    json.dump(report, sys.stdout, indent=2)
    print()
    sys.exit(0 if report["ok"] else 1)


if __name__ == "__main__":
    main()
